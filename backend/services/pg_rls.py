"""PostgreSQL row-level security: tenant isolation layer 2 (multi-tenancy phase 7).

Layer 1 is the session filter in :mod:`services.tenancy`; it sees ORM
statements only. This module is the net under it for everything else
(``text()`` SQL, Core statements on ``Model.__table__``, the bug nobody has
written yet):

* **Policies.** Every tenant-owned table gets ``ENABLE`` + ``FORCE ROW LEVEL
  SECURITY`` and one policy ``tenant_isolation`` (``FOR ALL``, the same
  expression for ``USING`` and ``WITH CHECK``)::

      current_setting('nodeglow.system', true) = 'on'
      OR tenant_id = NULLIF(current_setting('nodeglow.tenant_id', true), '')::integer

  ``NULLIF`` matters: once a custom setting has been set in a connection it
  reads ``''`` (not NULL) after the transaction, and ``''::integer`` raises.
  Neither setting → no row, and no row can be written (fail closed).
* **Settings per transaction.** :func:`install_engine_hooks` puts a
  ``before_cursor_execute`` hook on the engine that compares the tenant
  context (:func:`services.tenancy.current`, else the session's binding) with
  what this transaction last got, and if it differs runs
  ``set_config(..., true)`` first — transaction-local, so nothing survives the
  transaction or leaks through the pool. Per statement rather than once at
  ``BEGIN``, because one transaction may legitimately change context ("look
  the token up in system scope, continue in the row's tenant"). Cost: one
  extra round trip per transaction, plus one per context change.
* **Roles.** ``nodeglow_app`` — runtime DML, no ``BYPASSRLS``, owns nothing.
  The owner is whoever owns the schema and runs the migrations (the
  ``DATABASE_OWNER_URL`` user; in the Compose stack the ``POSTGRES_USER``).
  :func:`apply` creates ``nodeglow_app`` when it can, grants it DML on every
  table, and — when the app connects with its own login (``DATABASE_URL``
  differs from the owner URL) — creates or updates that login.

The switch is ``NODEGLOW_RLS`` (``config.RLS_ENABLED``): off, the policies
exist but RLS is disabled on the tables and the app sets no settings — the
behaviour of every install before phase 7. On, ``migrate.py`` enables and
forces RLS and the app sets the settings. See docs/OPERATIONS.md,
"Row-level security".

Known limit: the system bypass is a setting the application role can set
itself. RLS here is defence in depth against a forgotten tenant predicate,
not a boundary against SQL injection; a separate ``BYPASSRLS`` role for
system scope (the spec's ``nodeglow_system``) would be.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import logging
import os
from dataclasses import dataclass, field
from typing import Any, Iterable

from sqlalchemy import event, text

log = logging.getLogger("nodeglow.rls")

APP_ROLE = "nodeglow_app"
POLICY_NAME = "tenant_isolation"
# Stored as the policy's comment: a changed expression is recreated on the
# next run of migrate.py, an unchanged one is left alone (no lock).
POLICY_VERSION = "nodeglow-rls-1"
GUC_TENANT = "nodeglow.tenant_id"
GUC_SYSTEM = "nodeglow.system"

POLICY_EXPR = (
    f"current_setting('{GUC_SYSTEM}', true) = 'on' "
    f"OR tenant_id = NULLIF(current_setting('{GUC_TENANT}', true), '')::integer"
)

# Startup parameters for owner connections (migrations, restore): they act
# for the whole installation, and with FORCE ROW LEVEL SECURITY a
# non-superuser owner would otherwise see no rows in a data migration.
SYSTEM_SERVER_SETTINGS = {GUC_SYSTEM: "on"}


def quote_ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def quote_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def scram_sha256_verifier(password: str, *, iterations: int = 4096, salt: bytes | None = None) -> str:
    """The SCRAM-SHA-256 verifier PostgreSQL stores for ``password``.

    ``ALTER ROLE ... PASSWORD`` with a verifier instead of the plain password
    keeps the password out of the server log and ``pg_stat_statements``.
    (No SASLprep: passwords generated by install.sh are ASCII.)
    """
    salt = salt if salt is not None else os.urandom(16)
    salted = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, iterations)
    client_key = hmac.new(salted, b"Client Key", hashlib.sha256).digest()
    stored_key = hashlib.sha256(client_key).digest()
    server_key = hmac.new(salted, b"Server Key", hashlib.sha256).digest()

    def b64(raw: bytes) -> str:
        return base64.b64encode(raw).decode("ascii")

    return f"SCRAM-SHA-256${iterations}:{b64(salt)}${b64(stored_key)}:{b64(server_key)}"


# ── Configuration ────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class AppLogin:
    """The login the application connects as, when it is not the owner."""

    username: str
    password: str | None


def app_login(app_url: str | None = None, owner_url: str | None = None) -> AppLogin | None:
    """The app's own login from ``DATABASE_URL``, or None when the app
    connects as the owner (one URL — every install before phase 7)."""
    from sqlalchemy.engine import make_url

    import config

    app_url = app_url if app_url is not None else config.DATABASE_URL
    owner_url = owner_url if owner_url is not None else config.DATABASE_OWNER_URL
    if not app_url.startswith("postgresql"):
        return None
    app, owner = make_url(app_url), make_url(owner_url)
    if not app.username or app.username == owner.username:
        return None
    return AppLogin(username=app.username, password=app.password)


def system_connect_args(url: str) -> dict:
    """``connect_args`` for an engine that acts for the whole installation."""
    if url.startswith("postgresql+asyncpg"):
        return {"server_settings": dict(SYSTEM_SERVER_SETTINGS)}
    return {}


# ── Setup (owner connection, sync API: alembic and run_sync) ────────────────

@dataclass
class SetupReport:
    app_role: bool = False            # nodeglow_app exists (created or found)
    app_login: str | None = None      # separate login of the app, if configured
    rls_enabled: bool = False         # ENABLE + FORCE requested
    tables: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def warn(self, message: str) -> None:
        self.warnings.append(message)
        log.warning("%s", message)


def _scalar(conn, sql: str, **params):
    return conn.execute(text(sql), params).scalar()


def _try(conn, sql: str, report: SetupReport, what: str) -> bool:
    """Run one DDL statement in a savepoint; on failure warn and go on."""
    try:
        with conn.begin_nested():
            conn.exec_driver_sql(sql)
        return True
    except Exception as exc:  # noqa: BLE001 — permissions differ per environment
        orig = getattr(exc, "orig", None) or exc
        report.warn(f"{what}: {type(orig).__name__}: {str(orig).strip().splitlines()[0]}")
        return False


def _role_exists(conn, name: str) -> bool:
    return bool(_scalar(conn, "SELECT 1 FROM pg_roles WHERE rolname = :n", n=name))


def _role_flags(conn, name: str) -> tuple[bool, bool] | None:
    row = conn.execute(
        text("SELECT rolsuper, rolbypassrls FROM pg_roles WHERE rolname = :n"), {"n": name},
    ).first()
    return (bool(row[0]), bool(row[1])) if row else None


def tenant_tables_present(conn, tables: Iterable[str]) -> list[str]:
    """The given tables that exist in ``public`` and have a ``tenant_id``."""
    present = {
        r[0] for r in conn.execute(text(
            "SELECT table_name FROM information_schema.columns "
            "WHERE table_schema = 'public' AND column_name = 'tenant_id'"
        ))
    }
    return [t for t in tables if t in present]


def ensure_app_role(conn, login: AppLogin | None, report: SetupReport) -> bool:
    """Create ``nodeglow_app`` (and the app's login) if missing.

    Without CREATEROLE the statements fail; that is logged, never fatal: an
    upgrade must not stop because the database user is not allowed to manage
    roles (managed PostgreSQL). A DBA can create the roles by hand.
    """
    if not _role_exists(conn, APP_ROLE):
        if not _try(conn, f"CREATE ROLE {APP_ROLE} NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE",
                    report, f"cannot create role {APP_ROLE} (needs CREATEROLE)"):
            return False
    flags = _role_flags(conn, APP_ROLE)
    if flags and (flags[0] or flags[1]):
        if not _try(conn, f"ALTER ROLE {APP_ROLE} NOSUPERUSER NOBYPASSRLS", report,
                    f"{APP_ROLE} is superuser or BYPASSRLS and cannot be changed — "
                    "row-level security does not apply to it"):
            pass
    if login is None:
        return True

    report.app_login = login.username
    password = (" PASSWORD " + quote_literal(scram_sha256_verifier(login.password))) \
        if login.password else ""
    ident = quote_ident(login.username)
    if login.username == APP_ROLE:
        _try(conn, f"ALTER ROLE {APP_ROLE} LOGIN{password}", report,
             f"cannot set LOGIN/password of {APP_ROLE}")
    else:
        if not _role_exists(conn, login.username):
            _try(conn, f"CREATE ROLE {ident} LOGIN NOSUPERUSER NOBYPASSRLS{password}", report,
                 f"cannot create the app login {login.username}")
        elif password:
            _try(conn, f"ALTER ROLE {ident}{password}", report,
                 f"cannot set the password of {login.username}")
        if _role_exists(conn, login.username):
            _try(conn, f"GRANT {APP_ROLE} TO {ident}", report,
                 f"cannot grant {APP_ROLE} to {login.username}")
            flags = _role_flags(conn, login.username)
            if flags and (flags[0] or flags[1]):
                report.warn(f"the app login {login.username} is superuser or BYPASSRLS — "
                            "row-level security does not apply to it")
    return True


def grant_app_privileges(conn, report: SetupReport) -> None:
    """DML on every table and sequence of ``public`` for ``nodeglow_app``,
    now and for tables the owner creates later. Idempotent; ``migrate.py``
    re-runs it on every start, so a table added by a later revision is
    covered even before its own grant."""
    statements = [
        f"GRANT USAGE ON SCHEMA public TO {APP_ROLE}",
        f"GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO {APP_ROLE}",
        f"GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO {APP_ROLE}",
        f"ALTER DEFAULT PRIVILEGES IN SCHEMA public "
        f"GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO {APP_ROLE}",
        f"ALTER DEFAULT PRIVILEGES IN SCHEMA public "
        f"GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO {APP_ROLE}",
    ]
    for sql in statements:
        _try(conn, sql, report, f"cannot grant privileges to {APP_ROLE}")
    if _scalar(conn, "SELECT to_regclass('public.alembic_version')") is not None:
        # The app reads the schema revision; only migrations write it.
        _try(conn, f"REVOKE INSERT, UPDATE, DELETE ON alembic_version FROM {APP_ROLE}",
             report, "cannot restrict alembic_version")


def _policy_version(conn, table: str) -> str | None:
    """None: no policy; '': a policy without our comment; else the comment."""
    row = conn.execute(text(
        "SELECT COALESCE(d.description, '') FROM pg_policy p "
        "JOIN pg_class c ON c.oid = p.polrelid "
        "JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public' "
        "LEFT JOIN pg_description d ON d.objoid = p.oid "
        "  AND d.classoid = 'pg_policy'::regclass "
        "WHERE c.relname = :t AND p.polname = :p"
    ), {"t": table, "p": POLICY_NAME}).first()
    return None if row is None else row[0]


def ensure_policies(conn, tables: Iterable[str]) -> None:
    for table in tables:
        if _policy_version(conn, table) == POLICY_VERSION:
            continue
        ident = quote_ident(table)
        conn.exec_driver_sql(f"DROP POLICY IF EXISTS {POLICY_NAME} ON {ident}")
        conn.exec_driver_sql(
            f"CREATE POLICY {POLICY_NAME} ON {ident} FOR ALL "
            f"USING ({POLICY_EXPR}) WITH CHECK ({POLICY_EXPR})"
        )
        conn.exec_driver_sql(
            f"COMMENT ON POLICY {POLICY_NAME} ON {ident} IS {quote_literal(POLICY_VERSION)}"
        )


def rls_state(conn, tables: Iterable[str]) -> dict[str, tuple[bool, bool]]:
    """table → (row security enabled, forced)."""
    tables = list(tables)
    if not tables:
        return {}
    rows = conn.execute(text(
        "SELECT c.relname, c.relrowsecurity, c.relforcerowsecurity FROM pg_class c "
        "JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public' "
        "WHERE c.relkind IN ('r', 'p') AND c.relname = ANY(:t)"
    ), {"t": tables})
    return {r[0]: (bool(r[1]), bool(r[2])) for r in rows}


def set_rls(conn, tables: Iterable[str], enabled: bool) -> None:
    """ENABLE + FORCE (or DISABLE + NO FORCE), only where it differs."""
    for table, (on, forced) in rls_state(conn, tables).items():
        ident = quote_ident(table)
        if enabled:
            if not on:
                conn.exec_driver_sql(f"ALTER TABLE {ident} ENABLE ROW LEVEL SECURITY")
            if not forced:
                conn.exec_driver_sql(f"ALTER TABLE {ident} FORCE ROW LEVEL SECURITY")
        else:
            if forced:
                conn.exec_driver_sql(f"ALTER TABLE {ident} NO FORCE ROW LEVEL SECURITY")
            if on:
                conn.exec_driver_sql(f"ALTER TABLE {ident} DISABLE ROW LEVEL SECURITY")


def apply(conn, tables: Iterable[str], *, enabled: bool,
          login: AppLogin | None = None) -> SetupReport:
    """Bring roles, grants, policies and the RLS switch to the wanted state.

    Runs on an owner connection inside a transaction (alembic's, or
    ``engine.begin()`` + ``run_sync``). Role and grant problems are warnings;
    policy DDL on tables the connection owns cannot fail for lack of rights,
    so anything raised there is a real error.
    """
    report = SetupReport(rls_enabled=enabled)
    if conn.dialect.name != "postgresql":
        return report
    report.tables = tenant_tables_present(conn, tables)
    report.app_role = ensure_app_role(conn, login, report)
    if report.app_role:
        grant_app_privileges(conn, report)
    elif enabled:
        report.warn(
            f"role {APP_ROLE} is missing: row-level security is still forced on the "
            "tables, but it only protects a connection that is neither superuser nor "
            "BYPASSRLS — see docs/OPERATIONS.md, 'Row-level security'"
        )
    ensure_policies(conn, report.tables)
    set_rls(conn, report.tables, enabled)
    return report


def remove(conn, tables: Iterable[str]) -> None:
    """Drop the policies and switch RLS off (downgrade of 044).

    Roles and grants stay: an app already running as ``nodeglow_app`` keeps
    working without RLS, which is what a rollback is for. Roles are
    cluster-wide; dropping them is left to the DBA.
    """
    if conn.dialect.name != "postgresql":
        return
    present = tenant_tables_present(conn, tables)
    set_rls(conn, present, False)
    for table in present:
        conn.exec_driver_sql(f"DROP POLICY IF EXISTS {POLICY_NAME} ON {quote_ident(table)}")


# ── Runtime: the settings per transaction ────────────────────────────────────

# Keys in the DBAPI connection's info dict (pooled with the connection).
_STATE_KEY = "nodeglow_rls_settings"
_BOUND_KEY = "nodeglow_rls_bound_tenant"
# What a transaction that set nothing sees: no tenant, no system bypass.
CLEAN: tuple[str, str] = ("", "off")
# After ROLLBACK TO SAVEPOINT the value may be either; force a set.
_UNKNOWN: tuple[str, str] = ("?", "?")


def wanted_settings(ctx: Any, bound_tenant: int | None) -> tuple[str, str]:
    """(nodeglow.tenant_id, nodeglow.system) for a context — the same
    precedence as the session filter: ambient context, else the session's
    binding, else nothing (fail closed)."""
    if ctx is None:
        return (str(int(bound_tenant)), "off") if bound_tenant is not None else CLEAN
    if ctx.system:
        return ("", "on")
    if ctx.tenant_id is None:
        return CLEAN
    return (str(int(ctx.tenant_id)), "off")


def set_config_sql(settings: tuple[str, str]) -> str:
    tenant, system = settings
    # Both values are built here (an int and on/off), never user input.
    if tenant and not tenant.isdigit():
        raise ValueError(f"invalid tenant setting {tenant!r}")
    if system not in ("on", "off"):
        raise ValueError(f"invalid system setting {system!r}")
    return (f"SELECT set_config('{GUC_TENANT}', '{tenant}', true), "
            f"set_config('{GUC_SYSTEM}', '{system}', true)")


_SAVEPOINT_PREFIXES = ("SAVEPOINT", "RELEASE SAVEPOINT", "ROLLBACK TO SAVEPOINT")


def _is_savepoint_statement(statement: str) -> bool:
    head = statement[:24].lstrip().upper()
    return head.startswith(_SAVEPOINT_PREFIXES)


def _before_cursor_execute(conn, cursor, statement, parameters, context, executemany):
    from services import tenancy

    if _is_savepoint_statement(statement):
        # The session emits SAVEPOINT lazily, with the *first* statement
        # inside it — possibly already in another context. A setting made
        # just before it would be what ROLLBACK TO restores; the statement
        # that needs the settings sets them itself.
        return
    info = conn.info
    want = wanted_settings(tenancy.current(), info.get(_BOUND_KEY))
    if info.get(_STATE_KEY, CLEAN) == want:
        return
    # A separate cursor: the statement's own cursor is about to be used.
    cur = conn.connection.cursor()
    try:
        cur.execute(set_config_sql(want))
    finally:
        cur.close()
    info[_STATE_KEY] = want


def _transaction_boundary(conn, *args) -> None:
    conn.info[_STATE_KEY] = CLEAN


def _savepoint_rollback(conn, *args) -> None:
    conn.info[_STATE_KEY] = _UNKNOWN


def _pool_clear(dbapi_connection, connection_record, *args) -> None:
    if connection_record is not None:
        connection_record.info.pop(_STATE_KEY, None)
        connection_record.info.pop(_BOUND_KEY, None)


def _after_begin(session, transaction, connection) -> None:
    from services.tenancy import SESSION_TENANT_KEY

    connection.info[_BOUND_KEY] = session.info.get(SESSION_TENANT_KEY)


_session_hook_installed = False


def install_engine_hooks(engine) -> bool:
    """Set the tenant settings per transaction on this engine (sync or async).
    Idempotent; a no-op for anything but PostgreSQL."""
    global _session_hook_installed
    sync_engine = getattr(engine, "sync_engine", engine)
    if sync_engine.dialect.name != "postgresql":
        return False
    if getattr(sync_engine, "_nodeglow_rls_hooks", False):
        return True
    event.listen(sync_engine, "before_cursor_execute", _before_cursor_execute)
    for name in ("begin", "commit", "rollback"):
        event.listen(sync_engine, name, _transaction_boundary)
    event.listen(sync_engine, "rollback_savepoint", _savepoint_rollback)
    event.listen(sync_engine, "checkin", _pool_clear)
    event.listen(sync_engine, "reset", _pool_clear)
    sync_engine._nodeglow_rls_hooks = True
    if not _session_hook_installed:
        from sqlalchemy.orm import Session

        event.listen(Session, "after_begin", _after_begin)
        _session_hook_installed = True
    return True


def install_if_enabled(engine) -> bool:
    import config

    if not config.RLS_ENABLED:
        return False
    return install_engine_hooks(engine)


# ── Diagnostics ──────────────────────────────────────────────────────────────

def runtime_status(conn, tables: Iterable[str]) -> dict:
    """What the current connection is subject to (sync; use via run_sync)."""
    row = conn.execute(text(
        "SELECT current_user, rolsuper, rolbypassrls FROM pg_roles WHERE rolname = current_user"
    )).first()
    tables = list(tables)
    state = rls_state(conn, tables)
    owned = _scalar(conn, (
        "SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
        "WHERE n.nspname = 'public' AND c.relname = ANY(:t) "
        "AND pg_has_role(current_user, c.relowner, 'USAGE')"
    ), t=tables) if tables else 0
    return {
        "user": row[0] if row else None,
        "superuser": bool(row and row[1]),
        "bypassrls": bool(row and row[2]),
        "owns_tables": int(owned or 0),
        "tables": len(state),
        "enabled": sum(1 for on, _ in state.values() if on),
        "forced": sum(1 for _, forced in state.values() if forced),
    }


def assess(status: dict, flag: bool) -> list[tuple[int, str]]:
    """(log level, message) for a runtime status."""
    out: list[tuple[int, str]] = []
    total, enabled = status["tables"], status["enabled"]
    if not flag:
        if enabled:
            out.append((logging.ERROR, (
                f"row-level security is enabled on {enabled} of {total} tenant tables, but "
                "NODEGLOW_RLS is off: the app sets no tenant and those tables look empty. "
                "Set NODEGLOW_RLS=on, or run migrate.py to switch RLS off again."
            )))
        return out
    if enabled < total or status["forced"] < total:
        out.append((logging.ERROR, (
            f"NODEGLOW_RLS is on but row-level security is enabled/forced on only "
            f"{enabled}/{status['forced']} of {total} tenant tables — run migrate.py"
        )))
    if status["superuser"] or status["bypassrls"]:
        out.append((logging.WARNING, (
            f"NODEGLOW_RLS is on, but the app connects as {status['user']}, which is "
            f"{'a superuser' if status['superuser'] else 'BYPASSRLS'}: row-level security "
            f"does not apply. Connect as {APP_ROLE} (docs/OPERATIONS.md, 'Row-level security')."
        )))
    elif status["owns_tables"]:
        out.append((logging.INFO, (
            f"the app connects as the table owner {status['user']}; RLS applies because it "
            f"is forced, but the owner could switch it off — connect as {APP_ROLE}"
        )))
    return out


async def log_runtime_status(engine, tables: Iterable[str] | None = None) -> dict | None:
    """Log whether RLS protects the app's connection. Never raises."""
    import config

    sync_engine = getattr(engine, "sync_engine", engine)
    if sync_engine.dialect.name != "postgresql":
        return None
    try:
        if tables is None:
            from services.tenancy import tenant_tables

            tables = sorted(t.name for t in tenant_tables())
        tables = list(tables)
        async with engine.connect() as conn:
            status = await conn.run_sync(lambda c: runtime_status(c, tables))
    except Exception:  # noqa: BLE001 — diagnostics must not stop the start
        log.warning("could not check the row-level security state", exc_info=True)
        return None
    findings = assess(status, config.RLS_ENABLED)
    for level, message in findings:
        log.log(level, "%s", message)
    if config.RLS_ENABLED and not findings:
        log.info("row-level security active on %d tenant tables (app role %s)",
                 status["tables"], status["user"])
    return status
